import type { PanicPlan } from "../types/api";

export function formatPanicPlanForShare(plan: PanicPlan): string {
  const lines: string[] = [];
  
  lines.push(`UNISYNC SURVIVAL PLAN`);
  lines.push(``);
  lines.push(`${plan.headline}`);
  lines.push(``);
  lines.push(`PLAN (${plan.hours_available}h available):`);
  lines.push(``);
  
  plan.plan.forEach((item) => {
    lines.push(`${item.order}. ${item.title}`);
    lines.push(`   ${item.subject_name} · ${item.allocated_minutes}m`);
    lines.push(`   ${item.reason}`);
    lines.push(``);
  });
  
  if (plan.skip.length > 0) {
    lines.push(`SKIP THESE:`);
    lines.push(``);
    plan.skip.forEach((item) => {
      lines.push(`- ${item.title} (${item.reason})`);
    });
    lines.push(``);
  }
  
  lines.push(`Risk before: ${plan.projected.risk_before}`);
  lines.push(`Risk after: ${plan.projected.risk_after}`);
  lines.push(``);
  lines.push(`Generated by Unisync`);
  
  return lines.join("\n");
}
